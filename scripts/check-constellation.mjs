import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {JSDOM,VirtualConsole} from 'jsdom';
const html=readFileSync(new URL('../index.html',import.meta.url),'utf8');
const dom=new JSDOM(html,{url:'https://constellation.example',runScripts:'dangerously',virtualConsole:new VirtualConsole(),beforeParse(window){window.scrollTo=()=>{};}});
await new Promise(resolve=>dom.window.addEventListener('load',resolve,{once:true}));
const w=dom.window,d=w.document,app=w.cookieEmpire;
let checks=0;
function check(value,message){assert.ok(value,message);checks++;}
const visible=()=>[...d.querySelectorAll('[data-view]')].filter(x=>!x.hidden).map(x=>x.dataset.view).join(',');
check(visible()==='empire','Empire seul visible au départ');
const originalCard=d.querySelector('[data-generator-id="chocolate_lab"]');
for(const view of ['workshop','research','journey','empire']){
 d.querySelector(`[data-nav="${view}"]`).click();
 check(visible()===view,`vue ${view} exclusive`);
 check(d.querySelectorAll('[data-nav][aria-current="page"]').length===1,'navigation active unique');
 check(d.getElementById('quickClickBar').hidden===(view==='empire'),'clic secondaire selon vue');
}
check(originalCard===d.querySelector('[data-generator-id="chocolate_lab"]'),'cartes conservées');
const nav=d.querySelector('[data-nav="empire"]');
nav.dispatchEvent(new w.KeyboardEvent('keydown',{key:'ArrowRight',bubbles:true}));
check(visible()==='workshop' && d.activeElement.dataset.nav==='workshop','navigation clavier droite');
d.activeElement.dispatchEvent(new w.KeyboardEvent('keydown',{key:'End',bubbles:true}));
check(visible()==='journey','navigation clavier fin');
const s=app.state;s.cookies=w.eval('HugeNumber.from(183000000)');s.totalProduced=s.cookies.clone();
Object.assign(s.generators,{cursor:87,grandma:61,oven:55,cocoa_mine:58,chocolate_lab:45});
s.ownedUpgrades=['reinforced_click','efficient_cursor','grandma_recipe','warm_ovens','cocoa_excavators','cosmic_click'];
w.eval('Economy.refreshDerived(cookieEmpire.state)');app.ui.render();
check(d.getElementById('balance').textContent==='183 M','état vidéo compact');
check(d.getElementById('balance').getAttribute('aria-label').includes('million'),'réserve complète accessible');
check(d.getElementById('sceneObjective').textContent==='Première mise en orbite','suite réelle pour état vidéo');
const prior=s.cookies.clone(),reward=s.clickReward.clone(),clicks=s.totalClicks;
d.getElementById('quickCookie').click();
check(s.cookies.compare(prior.add(reward))===0 && s.totalClicks===clicks+1,'clic secondaire réel');
let renders=0;const render=app.ui.render.bind(app.ui);app.ui.render=()=>{renders++;render();};
for(let i=0;i<100;i++)app.ui.handleClick();
check(renders===0,'clics rapides sans reconstruction de boutique');
check(s.totalClicks===clicks+101,'cent clics jamais perdus');
app.ui.render=render;app.ui.selectView('research');
const precision=d.querySelector('[data-upgrade-id="precision_click"]'),quantum=d.querySelector('[data-upgrade-id="quantum_click"]');
check(!precision.disabled && quantum.disabled,'branche verrouillée correctement');
const beforePrecision=s.clickReward.clone();precision.click();
check(s.clickReward.compare(beforePrecision.multiply(2))===0,'recherche double vraiment clic');
check(!quantum.disabled,'successeur devient disponible');
quantum.click();check(s.ownedUpgrades.includes('quantum_click'),'achat successeur');
check(d.querySelector('[data-generator-id="chocolate_lab"] .click-bonus').textContent.includes('5.52 mille'),'contribution unitaire avec multiplicateurs');
d.querySelector('[data-branch="globalCps"]').click();
check(precision.closest('.upgrade-card').hidden,'filtre branche');
d.querySelector('[data-branch="click"]').click();d.getElementById('researchFilter').click();
check(precision.closest('.upgrade-card').hidden,'acquises masquées');
d.querySelector('[data-research-jump="quantum_click"]').click();
check(!quantum.closest('.upgrade-card').hidden && d.activeElement.id==='research-quantum_click','prérequis retrouvé malgré filtres');
check(app.ui.hideOwnedResearch===false && app.ui.researchBranch==='all','filtres remis à zéro');
const raw=app.saveSystem.encode(s),reloaded=app.saveSystem.decode(raw);
check(reloaded.generators.chocolate_lab===45 && reloaded.ownedUpgrades.includes('quantum_click'),'sauvegarde compatible');
check(reloaded.clickReward.compare(s.clickReward)===0,'gain rechargé exact');
s.cookies=w.eval('HugeNumber.from("1e1000")');app.ui.render();
check(d.getElementById('balance').textContent==='1e1000','affichage extrême');
check(d.querySelectorAll('[id]').length===new Set([...d.querySelectorAll('[id]')].map(x=>x.id)).size,'identifiants uniques');
for(const mode of ['light','dark']){app.ui.applyTheme(mode);check(d.documentElement.dataset.theme===mode,'thème '+mode);}
check(!d.querySelector('script[src],link[rel="stylesheet"],img[src^="http"]'),'jeu autonome');
const old=app.state;check(app.resetGame(),'reset réussi');check(app.state!==old && app.state.generators.stellar_forge===0 && app.state.clickReward.compare(1)===0,'nouvelle partie cohérente');
console.log(`Constellation : ${checks} vérifications DOM réussies (simulation jsdom)`);
w.close();
